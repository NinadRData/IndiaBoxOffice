(function () {
  'use strict';

  function key(title, year) {
    return String(year) + ':' + String(title || '')
      .toLowerCase()
      .normalize('NFKD')
      .replace(/[\u0300-\u036f]/g, '')
      .replace(/[^a-z0-9]/g, '');
  }

  function validDate(value) {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(value || '')) {
      return false;
    }

    var date = new Date(value + 'T00:00:00Z');

    return (
      Number.isFinite(date.getTime()) &&
      date.toISOString().slice(0, 10) === value
    );
  }

  function validatedDays(film) {
    if (!validDate(film.release) || !Array.isArray(film.days)) {
      return null;
    }

    var first = Date.parse(film.release + 'T00:00:00Z');
    var byDay = Object.create(null);
    var maximum = 0;

    for (var i = 0; i < film.days.length; i++) {
      var row = film.days[i];

      if (
        !row ||
        !Number.isInteger(row.day) ||
        row.day < 1 ||
        row.day > 366 ||
        !Number.isFinite(row.indiaNet) ||
        row.indiaNet < 0 ||
        byDay[row.day]
      ) {
        return null;
      }

      var expected = new Date(
        first + (row.day - 1) * 86400000
      ).toISOString().slice(0, 10);

      if (row.date !== expected) return null;

      byDay[row.day] = row;
      maximum = Math.max(maximum, row.day);
    }

    return maximum
      ? { first: first, byDay: byDay, maximum: maximum }
      : null;
  }

  function makePanel(film, page, data) {
    var panel = document.createElement('details');

    panel.dataset.sourcedHistoryConflict = '';

    panel.style.cssText =
      'margin:24px auto;padding:18px;max-width:960px;' +
      'border:1px solid #80551b;border-radius:10px;' +
      'background:#211a12;color:#f1e4ce';

    var summary = document.createElement('summary');

    summary.textContent =
      'Release-date conflict: view sourced daily India net';

    summary.style.cursor = 'pointer';
    panel.appendChild(summary);

    var note = document.createElement('p');

    note.textContent =
      'Manual page: ' + page.release +
      ' · Historical feed: ' + film.release +
      '. The figures below are separate; the existing page ' +
      'and tracking data have not been replaced.';

    panel.appendChild(note);

    var list = document.createElement('div');

    list.style.cssText =
      'max-height:420px;overflow:auto;font-size:14px';

    var sum = 0;
    var complete = true;

    for (var day = 1; day <= data.maximum; day++) {
      var row = data.byDay[day];

      var date = new Date(
        data.first + (day - 1) * 86400000
      ).toISOString().slice(0, 10);

      var line = document.createElement('div');

      line.style.cssText =
        'padding:5px 0;border-top:1px solid #50412f';

      if (!row) {
        complete = false;

        line.textContent =
          'Day ' + day + ' · ' + date +
          ' · No daily report available';
      } else {
        if (complete) {
          sum = Math.round((sum + row.indiaNet) * 100) / 100;
        }

        var amount = row.indiaNet.toLocaleString('en-IN', {
          maximumFractionDigits: 2
        });

        var sumText = complete
          ? ' · Reported sum ₹' +
            sum.toLocaleString('en-IN', {
              maximumFractionDigits: 2
            }) +
            ' Cr'
          : ' · Sum unavailable after missing day';

        line.textContent =
          'Day ' + day + ' · ' + date +
          ' · ₹' + amount + ' Cr' + sumText;
      }

      list.appendChild(line);
    }

    panel.appendChild(list);
    return panel;
  }

  fetch('data/historical.json', { cache: 'no-cache' })
    .then(function (response) {
      if (!response.ok) {
        throw new Error('Historical feed unavailable');
      }

      return response.json();
    })
    .then(function (history) {
      if (
        !history ||
        history.kind !== 'historical' ||
        !Array.isArray(history.films) ||
        typeof FILM_PAGES === 'undefined'
      ) {
        return;
      }

      function render() {
        var pages = Object.keys(FILM_PAGES)
          .map(function (id) {
            return FILM_PAGES[id];
          })
          .filter(function (page, i, all) {
            return (
              page &&
              page.key &&
              page.title &&
              !page.autoGenerated &&
              all.indexOf(page) === i
            );
          });

        pages.forEach(function (page) {
          if (!validDate(page.release)) return;

          var node = document.getElementById(
            'page-film-' + page.key
          );

          if (
            !node ||
            node.querySelector('[data-sourced-history-conflict]')
          ) {
            return;
          }

          var explicit = page.sacnilkUrl || page.sourceUrl;

          var matches = history.films.filter(function (film) {
            if (!film || film.year !== page.year) {
              return false;
            }

            return explicit
              ? film.url === explicit
              : key(film.title, film.year) ===
                  key(page.title, page.year);
          });

          if (
            matches.length !== 1 ||
            matches[0].release === page.release
          ) {
            return;
          }

          if (!explicit) {
            var matchingPages = pages.filter(function (other) {
              return key(other.title, other.year) ===
                key(page.title, page.year);
            });

            if (matchingPages.length !== 1) return;
          }

          var data = validatedDays(matches[0]);

          if (data) {
            node.appendChild(
              makePanel(matches[0], page, data)
            );
          }
        });
      }

      render();

      var timer;

      new MutationObserver(function () {
        clearTimeout(timer);
        timer = setTimeout(render, 100);
      }).observe(document.body, {
        childList: true,
        subtree: true
      });
    })
    .catch(function (error) {
      console.warn('Sourced history unavailable:', error);
    });
})();
