(function () {
  var aliases = {
    '2026:ramayana': 'ramayanapart1',
    '2026:dhurandhar2therevenge': 'dhurandhar2',
    '2026:drishyam3theconclusion': 'drishyamtheconclusion',
    '2026:bhoothbangla': 'bhootbhangla',
    '2025:kantaraalegendchapter1': 'kantarachapter1',
    '2025:mahavatarnarsimha': 'mahavtarnarsimha'
  };

  var months = [
    'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
    'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'
  ];

  var weekdays = [
    'Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'
  ];

  function id(title, year) {
    var name = String(title || '')
      .toLowerCase()
      .normalize('NFKD')
      .replace(/[\u0300-\u036f]/g, '')
      .replace(/[^a-z0-9]/g, '');

    var key = String(year) + ':' + name;
    return String(year) + ':' + (aliases[key] || name);
  }

  function pct(current, previous) {
    return previous > 0
      ? Math.round((current / previous - 1) * 1000) / 10
      : null;
  }

  function rowDateMatches(text, date) {
    var wanted = date.toISOString().slice(0, 10);

    var first = date.getUTCDate() + ' ' +
      months[date.getUTCMonth()];

    var second = months[date.getUTCMonth()] + ' ' +
      date.getUTCDate();

    var cleaned = String(text).replace(/\s+/g, ' ').trim();

    if (cleaned.indexOf(wanted) !== -1) return true;

    return new RegExp(
      '(?:^|[^a-z0-9])(?:' + first + '|' + second + ')' +
      '(?:$|[^a-z0-9])',
      'i'
    ).test(cleaned);
  }

  function prepare(source, page) {
    if (
      !source ||
      !page ||
      page.autoGenerated ||
      !Array.isArray(source.days) ||
      !/^\d{4}-\d{2}-\d{2}$/.test(page.release || '')
    ) return null;

    var release = new Date(page.release + 'T00:00:00Z');
    if (!Number.isFinite(release.getTime())) return null;
    // A malformed row must not prevent other film pages from syncing.
    if (source.days.some(function (row) {
      return !row || typeof row !== 'object';
    })) return null;

    var rows = source.days.slice().sort(function (a, b) {
      return a.day - b.day;
    });
        // Historical reports can have missing days. Only use the
    // consecutive run so cumulative totals don't skip those gaps.
    if (source.historical) {
      var end = rows.findIndex(function (row, i) {
        return !row || row.day !== i + 1;
      });

      if (end !== -1) {
        rows = rows.slice(0, end);
      }
    }

    var oldRows = page.daily == null ? [] : page.daily;

    if (
      !Array.isArray(oldRows) ||
      !rows.length ||
      rows.length < oldRows.length
    ) return null;

    // Require consecutive source days that agree with release date.
    for (var i = 0; i < rows.length; i++) {
      var row = rows[i];

      var expected = new Date(
        release.getTime() + i * 86400000
      );

      if (
        !row ||
        row.day !== i + 1 ||
        row.date !== expected.toISOString().slice(0, 10) ||
        !Number.isFinite(row.indiaNet) ||
        row.indiaNet < 0
      ) return null;
    }

    var saved = {};

    for (var j = 0; j < oldRows.length; j++) {
      var old = oldRows[j];

      // Don't overwrite grouped or preview rows.
      if (
        !old ||
        old.bucket ||
        old.preview ||
        typeof old.date !== 'string'
      ) return null;

      var found = -1;

      for (var x = 0; x < rows.length; x++) {
        var date = new Date(rows[x].date + 'T00:00:00Z');

        if (rowDateMatches(old.date, date)) {
          if (found !== -1) return null;
          found = x;
        }
      }

      if (
        found < 0 ||
        Object.prototype.hasOwnProperty.call(saved, found)
      ) return null;

      saved[found] = old;
    }

    var total = 0;

    return rows.map(function (row, index) {
      var date = new Date(row.date + 'T00:00:00Z');
      total = Math.round((total + row.indiaNet) * 100) / 100;

      return Object.assign({}, saved[index] || {}, {
        date: date.getUTCDate() + ' ' +
          months[date.getUTCMonth()],
        day: weekdays[date.getUTCDay()],
        gross: row.indiaNet,
        total: total,
        chgDay: index
          ? pct(row.indiaNet, rows[index - 1].indiaNet)
          : null,
        chgWeek: index >= 7
          ? pct(row.indiaNet, rows[index - 7].indiaNet)
          : null
      });
    });
  }

  function load(path) {
    return fetch(path, { cache: 'no-cache' })
      .then(function (response) {
        if (!response.ok) throw new Error(path);
        return response.json();
      })
      .catch(function () {
        return null;
      });
  }

    Promise.all([
    window.loadDailyFeeds(),
    load('data/historical.json')
  ])
    .then(function (results) {
      if (typeof FILM_PAGES === 'undefined') return;

      var liveFeeds = results[0];
      var historical = results[1];
      var liveUrls = Object.create(null);

      // An older historical record must not bypass an ambiguous
      // or conflicting record in either live feed.
      liveFeeds.forEach(function (documentData) {
        if (!documentData || !Array.isArray(documentData.films)) {
          return;
        }

        documentData.films.forEach(function (film) {
          if (film && typeof film.url === 'string') {
            liveUrls[film.url] = true;
          }
        });
      });

      // Use the same live-feed selection as the chart and tracker.
      var sourceList = window.resolveDailyFeeds(
        liveFeeds[0],
        liveFeeds[1]
      )
        .filter(function (record) {
          return Number.isFinite(record.stamp);
        })
        .map(function (record) {
          return record.film;
        });

      // Use saved historical data only when neither live feed
      // contains that source URL.
      if (
        historical &&
        historical.kind === 'historical' &&
        Array.isArray(historical.films)
      ) {
        historical.films.forEach(function (film) {
          if (
            !film ||
            liveUrls[film.url] ||
            typeof film.title !== 'string' ||
            !Number.isInteger(film.year) ||
            !/^https:\/\/www\.sacnilk\.com\/movie\/[A-Za-z0-9_-]+$/.test(
              film.url || ''
            ) ||
            !Number.isFinite(
              Date.parse(
                film.fetchedAt || historical.updatedAt || ''
              )
            )
          ) {
            return;
          }

          sourceList.push(
            Object.assign({}, film, { historical: true })
          );
        });
      }


      var pages = Object.keys(FILM_PAGES)
        .map(function (key) {
          return FILM_PAGES[key];
        })
        .filter(function (page, index, all) {
          return page &&
            page.key &&
            page.title &&
            !page.autoGenerated &&
            all.indexOf(page) === index;
        });

      var changed = 0;

      pages.forEach(function (page) {
        var explicit = page.sacnilkUrl || page.sourceUrl;

        var matches = sourceList.filter(function (film) {
          if (explicit) {
            return film.url === explicit &&
              film.year === page.year;
          }

          return film.year === page.year &&
            id(film.title, film.year) ===
              id(page.title, page.year);
        });

        if (matches.length !== 1) return;

        if (
          !explicit &&
          pages.filter(function (other) {
            return other.year === page.year &&
              id(other.title, other.year) ===
                id(page.title, page.year);
          }).length !== 1
        ) return;
        var sourceRelease = matches[0].release;

        if (
          /^\d{4}-\d{2}-\d{2}$/.test(sourceRelease || '') &&
          /^\d{4}-\d{2}-\d{2}$/.test(page.release || '') &&
          sourceRelease !== page.release
        ) {
          console.warn(
            'Daily sync skipped: release-date conflict for',
            page.title,
            '(manual:', page.release + '; source:', sourceRelease + ').'
          );
          return;
        }

        var merged = prepare(matches[0], page);
        if (!merged) return;

        page.daily = merged;
        changed++;

        // Refresh the page if it was already open.
        var open = document.getElementById(
          'page-film-' + page.key
        );

        if (open && open.classList.contains('active')) {
          var scroll = window.scrollY;

          if (
            page.prediction &&
            typeof showFilmPageWithPredictions === 'function'
          ) {
            showFilmPageWithPredictions(page.key);
          } else if (typeof showFilmPage === 'function') {
            showFilmPage(page.key);
          }

          window.scrollTo(0, scroll);
        }
      });

      if (changed && typeof renderTraj === 'function') {
        renderTraj();
      }

      console.log(
        'Daily sync: updated',
        changed,
        'manual film page(s).'
      );
    })
    .catch(function (error) {
      console.warn('Daily sync unavailable:', error);
    });
})();
